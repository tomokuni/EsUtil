namespace EsUtil.Platform.Core.Imaging;

/// <summary>減色するときのディザ（誤差拡散）の指定。</summary>
/// <remarks>
/// <b>ディザとは何か</b>: 減色で残せる色は 256 色以下であるため、グラデーションのような連続した色は<b>縞（バンディング）</b>に
/// なります。 ディザは画素を置き換えたときの誤差をとなりへ配り、<b>近寄って見ると元の色に戻る</b>ようにパレットの色を
/// 交互に置きます。
///
/// <list type="table">
/// <item>
///   <term><see cref="None"/></term>
///   <description><b>既定</b>。 画素ごとに最も近いパレットの色へ置き換える。 <b>保存のファイルが最も小さくなる</b>
///   （縞は残る）。</description>
/// </item>
/// <item>
///   <term><see cref="FloydSteinberg"/></term>
///   <description>Floyd–Steinberg 法（誤差を右 7/16・下 5/16・左下 3/16・右下 1/16 の 4 画素へ配る）。</description>
/// </item>
/// </list>
///
/// <b>測り方（実測）</b>: ディザは<b>1 画素ごとの誤差を増やします</b>（1 つの画素は元の色から遠いパレットの色になるため）。
/// 目的は「離れて見たときに元の色に戻る」ことであるため、<b>8x8 のブロック平均の差</b>で測ります
/// （1024x768 の画像・<see cref="EsImageQuality.Mid"/>）:
///
/// <list type="table">
/// <item><term>16 色</term><description>1 画素（1 チャネル平均絶対誤差）16.6 → 17.2（悪化）、
/// <b>8x8 ブロック平均 8.9 → 4.2</b>（<b>縞が消える</b>）。 知覚誤差（CIEDE2000 の平均）8.3 → 10.1（悪化）。</description></item>
/// <item><term>256 色</term><description>1 画素 4.1 → 5.1（悪化）、8x8 ブロック平均 0.9 → <b>1.4（悪化）</b>。
/// 知覚誤差 2.1 → 2.7（悪化）。</description></item>
/// <item><term>平坦な色の画像（スクリーンショット風）</term><description>すべて 0.00 のまま（<b>変化しない</b>）。</description></item>
/// </list>
///
/// <b>勧める場合と勧めない場合</b>: <b>色数が内容に対して足りないとき（16 色など）は縞が消え、8x8 の差が半分になります</b>。
/// 一方 <b>256 色のように足りている場合</b>は、直すべき縞が無いのに画素へむらを加えるため、局所平均でもわずかに悪くなります
/// （実測: 0.9 → 1.4）。 また<b>もともと平坦な画像では何も変わりません</b>（誤差が 0 の画素には何も配られないため）。
///
/// <b>ファイルは大きくなる（実測。 1920x1080 の PNG）</b>: 写真風の画像は 16 色で 345,869 B → <b>529,910 B</b>、
/// 256 色で 1,054,573 B → 1,202,532 B。 <b>平坦な色の画像は変化しません</b>（47,691 B のまま）。
/// パレットの色を交互に置くと<b>隣り合う画素が変わる</b>ため、PNG の圧縮が効かなくなるためです。
///
/// <b>所要（実測。 1920x1080・256 色・<see cref="EsImageQuality.Mid"/>）</b>: 平坦な色の画像 13 ms →
/// 27 ms、写真風 19 ms → 43 ms、ノイズ 64 ms → 99 ms です（誤差の配布が画素ごとに加わり、加えて
/// <b>参照表を全域（131,072 箱）へ広げる</b>ため。 誤差を加えた色は画素が無かった色になりうるためです）。
///
/// <b>透過との関係</b>: 誤差を配るのは RGB だけで、アルファは画素ごとのパレットの色（減色で量子化された値）のままです
/// （誤差をアルファへ配ると、透明と不透明の境目がにじみます）。
/// </remarks>
public enum EsDitherMode
{
    /// <summary>ディザを行わない（既定。 ファイルが最も小さい）。</summary>
    None,

    /// <summary>Floyd–Steinberg 法の誤差拡散を行う（色数が足りないときの縞を消す。 ファイルは大きい）。</summary>
    FloydSteinberg,
}
