namespace EsUtil.Platform.Core.Imaging;

/// <summary>減色するときのディザ（誤差拡散）の指定。</summary>
/// <remarks>
/// <b>ディザとは何か</b>: 減色で残せる色は 256 色以下であるため、グラデーションのような連続した色は<b>縞（バンディング）</b>に
/// なります。 ディザは画素を置き換えたときの誤差をとなりへ配り、<b>近寄って見ると元の色に戻る</b>ようにパレットの色を
/// 交互に置きます。
///
/// <list type="table">
/// <item>
///   <term><see cref="None"/></term>
///   <description><b>既定</b>。 画素ごとに最も近いパレットの色へ置き換える。 <b>保存のファイルが最も小さくなる</b>
///   （縞は残る）。</description>
/// </item>
/// <item>
///   <term><see cref="FloydSteinberg"/></term>
///   <description>Floyd–Steinberg 法（誤差を右 7/16・下 5/16・左下 3/16・右下 1/16 の 4 画素へ配る）。</description>
/// </item>
/// </list>
///
/// <b>測り方（実測）</b>: ディザは<b>1 画素ごとの誤差を増やします</b>（1 つの画素は元の色から遠いパレットの色になるため）。
/// 目的は「離れて見たときに元の色に戻る」ことであるため、<b>8x8 のブロック平均の差</b>で測ります
/// （1024x768 の画像・<see cref="ImageQuality.Mid"/>）:
///
/// <list type="table">
/// <item><term>グラデーション 16 色</term><description>画素ごと 10.6 → <b>13.2</b>（悪化）、8x8 ブロック平均 10.2 → <b>4.0</b>（<b>縞が消える</b>）。</description></item>
/// <item><term>写真風 16 色</term><description>画素ごと 12.6 → 15.3（悪化）、8x8 ブロック平均 5.9 → <b>2.7</b>。</description></item>
/// <item><term>グラデーション 256 色</term><description>画素ごと 2.8 → 3.8（悪化）、8x8 ブロック平均 2.3 → <b>1.6</b>。</description></item>
/// <item><term>写真風 256 色</term><description>画素ごと 3.2 → 4.0、8x8 ブロック平均 0.8 → <b>1.4（悪化）</b>。</description></item>
/// <item><term>ノイズ 256 色</term><description>画素ごと 7.8 → 8.8、8x8 ブロック平均 1.0 → <b>1.4（悪化）</b>。</description></item>
/// <item><term>スクリーンショット風（平坦な色）</term><description>画素ごと 0.00 → 0.00、8x8 ブロック平均 0.00 → 0.00（<b>変化しない</b>）。</description></item>
/// </list>
///
/// <b>勧める場合と勧めない場合</b>: <b>色数が内容に対して足りないとき（16 色など）は縞が消え、8x8 の差が半分以下になります</b>。
/// 一方 <b>256 色のように足りている場合</b>は、直すべき縞が無いのに画素へむらを加えるため、局所平均でもわずかに悪くなります
/// （実測: 写真風 0.8 → 1.4、ノイズ 1.0 → 1.4）。 また<b>もともと平坦な画像では何も変わりません</b>（誤差が 0 の画素には
/// 何も配られないため）。
///
/// <b>ファイルは大きくなる（実測。 1920x1080 の 256 色 PNG）</b>: グラデーション 17,830 B → <b>319,481 B</b>、
/// 写真風 495,932 B → 603,078 B。 <b>平坦な色の画像は変化しません</b>（スクリーンショット風は 12,916 B のまま）。
/// パレットの色を交互に置くと<b>隣り合う画素が変わる</b>ため、PNG の圧縮が効かなくなるためです。
///
/// <b>透過との関係</b>: 誤差を配るのは RGB だけで、アルファは画素ごとのパレットの色（減色で量子化された値）のままです
/// （誤差をアルファへ配ると、透明と不透明の境目がにじみます）。
/// </remarks>
public enum DitherMode
{
    /// <summary>ディザを行わない（既定。 ファイルが最も小さい）。</summary>
    None,

    /// <summary>Floyd–Steinberg 法の誤差拡散を行う（色数が足りないときの縞を消す。 ファイルは大きい）。</summary>
    FloydSteinberg,
}
