namespace EsUtil.Platform.Core.Imaging;

/// <summary>コアの画像を縮小するときのアルゴリズム（<see cref="EsBitmapExtensions.Resize"/> の引数）。</summary>
/// <remarks>
/// <b>どれを選ぶか</b>（実測は Release・4K 3840x2160 の画像。 環境によりぶれるため桁で見ること。
/// 表中の値はすべて<b>縮小先の行を並列実行する実装</b>のもので、逐次より 3〜13 倍速い）:
///
/// <list type="table">
/// <item>
///   <term><see cref="Nearest"/></term>
///   <description>最速（4K → 96x54 で 11 µs・4K → 320x180 で 63 µs）。 縮小先の 1 画素につき元の 1 画素（比例位置）だけを
///   読む。<b>縮小率が大きいと内容が落ちる</b>（実測: 40 倍の縮小で幅 1 px の細線は輝度 0。 位置が合えばそのまま残るため
///   結果が位置に依存する）。 <b>向く用途</b>: 単色・写真のサムネイル、縮小率が 2 倍程度の場面。</description>
/// </item>
/// <item>
///   <term><see cref="Bilinear"/></term>
///   <description>速さと画質の釣り合い（4K → 96x54 で 68 µs・4K → 320x180 で 237 µs、960x540 で 1.0 ms）。
///   元の 2x2 画素を重み付き平均する。
///   <b>既定</b>。 40 倍の縮小では細線が落ちる（2x2 しか見ないため）。 <b>向く用途</b>: 表示用のサムネイル（縮小率 2〜10 倍）。</description>
/// </item>
/// <item>
///   <term><see cref="Box"/></term>
///   <description>最も画質が高い（面積平均 = box フィルター）。 縮小先の 1 画素を、対応する元画像の矩形（全画素）の平均で作るため
///   <b>細線（文字・罫線）が落ちない</b>（実測: 40 倍の縮小で輝度 6。 最近傍 0 / 双線形 0 / GDI+ の高画質 4）。
///   速度は<b>元画像の画素数</b>で決まり縮小先の寸法にはよらない（4K で 1 枚 1.5〜2.0 ms）。
///   <b>向く用途</b>: 文字・罫線を判読したいサムネイル、保存用の縮小、ファイルのサムネイル（コーデックの縮小デコードで得られる画質と同じ）。<br/>
///   <b>立方畳み込み（bicubic）とは別のアルゴリズムである</b>（本値は元の矩形の等重み平均であり負の重みを持たない。
///   立方畳み込みは負の重みを持つ復元フィルタであり、縮小では結果が違う。 実測: GDI+ の `HighQualityBicubic` との
///   画素の最大差は 12 倍縮小で 33・2 倍縮小で 113。 厳密な面積平均との差は本値 0.37 に対し `HighQualityBicubic` 1.6）。
///   <b>縮小で本値に相当するのは GDI+ の `Bilinear`</b>（厳密な面積平均との差 0.20）と Skia の `Linear + ミップ`（差 1.6）である。
///   したがって本値の名前を `Bicubic` へ変えない（名前がアルゴリズムと食い違う）。</description>
/// </item>
/// </list>
///
/// <b>立方畳み込み（bicubic）をアルゴリズムへ加えない理由（実測）</b>: 試作して確かめたところ、縮小では
/// <see cref="Box"/> が最も速く最も正しい（12 倍縮小で 1.6 ms・厳密な面積平均との差 0.37 に対し、
/// 縮小率に応じて支持幅を広げた立方畳み込みは 12.9 ms・1.30）。 2 倍縮小では鮮鋭さでも負ける
/// （隣接差は <see cref="Box"/> 21.3 対 立方畳み込み 13.1。 立方畳み込みの方が柔らかくなる）。
/// 固定 4 タップ版は 0.72 ms と安いが、それは<b>間引くだけ</b>であり面積平均との差は 13.4（<see cref="Bilinear"/> の 10.6 と同程度）。
/// 立方畳み込みが正しい選択になるのは<b>拡大</b>であり、本メソッドは拡大を行わない。
///
/// <b>同じ機能の別名を作らない</b>ためにアルゴリズムは本列挙体で選び、入口は <see cref="EsBitmapExtensions.Resize"/> の 1 つに統一する。
/// </remarks>
public enum DownscaleAlgorithm
{
    /// <summary>最近傍補間（最速。 縮小率が大きいと細線が落ちる）。</summary>
    Nearest,

    /// <summary>双線形補間（既定。 元の 2x2 を平均する）。</summary>
    Bilinear,

    /// <summary>面積平均（box フィルター。 最も画質が高く、元画像の画素数に比例して遅い）。</summary>
    Box,
}
