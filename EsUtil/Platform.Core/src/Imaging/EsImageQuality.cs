namespace EsUtil.Platform.Core.Imaging;

/// <summary>画像を変換するときの品質（速度と画質の釣り合い。 縮小と減色が使う）。</summary>
/// <remarks>
/// <b>3 段階の意味は操作ごとに決まる</b>（どちらも「低いほど速く画質が低い」であり、段階の数え方は同じ）:
///
/// <list type="table">
/// <item>
///   <term><see cref="Low"/></term>
///   <description><b>最速</b>。 <b>縮小</b>は最近傍補間（縮小先の 1 画素につき元の 1 画素だけを読む）、
///   <b>減色</b>は中央値分割で分けた箱の平均色をそのまま使う（色の詰め直しを行わない）。</description>
/// </item>
/// <item>
///   <term><see cref="Mid"/></term>
///   <description><b>既定</b>。 <b>縮小</b>は双線形補間（元の 2x2 画素を重み付き平均する）、<b>減色</b>は中央値分割の
///   結果を反復（k-means）で詰め直す（「使われている箱の数 × 色数」で決まる作業量の上限つき）。</description>
/// </item>
/// <item>
///   <term><see cref="High"/></term>
///   <description><b>最も画質が高い</b>。 <b>縮小</b>は面積平均（box フィルター。 縮小先の 1 画素を対応する元の矩形の
///   平均で作るため、文字・罫線が落ちない）、<b>減色</b>は反復の上限（8 回）と時間の上限（500 ms）の
///   どちらか先に達するまで詰め直す。</description>
/// </item>
/// </list>
///
/// <b>縮小の速さの順序</b>: <see cref="Low"/> が最も速く、<see cref="High"/> が最も遅い。
/// <b><see cref="High"/> の費用は元画像の画素数で決まり、縮小先の寸法にはよらない</b>ため、縮小先が大きい場合は
/// <see cref="Mid"/> より速くなることがある（<see cref="Mid"/> は縮小先の 1 画素につき元の 4 画素を読む）。
/// 細線が残るのは <see cref="High"/> であり、<see cref="Low"/> と <see cref="Mid"/> は落としやすい
/// （<see cref="Low"/> は位置が合えば残る）。 立方畳み込み（bicubic）を段階へ加えない理由は
/// <see cref="EsReadOnlyBitmap.Resize(int, EsImageQuality)"/> の備考を参照する。
///
/// <b>減色では <see cref="High"/> の知覚誤差が <see cref="Low"/> より小さくなる</b>
/// （知覚誤差は CIEDE2000 の平均で、小さいほど良い）: <b>色数が少ないほど効果が大きい</b>。
/// <b><see cref="High"/> は <see cref="Mid"/> と同じ結果になる場合が多い</b>: 使われている箱が多い画像だけに
/// 効き、詰め直しの回数だけ費用が増える（画質の差は小さい）。
/// グラデーションと写真風は既定の作業量の上限でも収束するため<b>同じ結果</b>になる。
///
/// <b>減色には所要の上限（正味 500 ms の安全網）がある</b>: <b>減色</b>の <see cref="High"/> は「改善が止まるまで」
/// 反復するため、わずかずつ改善し続ける画像では反復の上限（8 回）まで回る。 反復に与える時間は
/// <b>減色の計算を始めてから 500 ms</b> とし、過ぎたら採用済みのパレットで止める（この部分だけが中断できる。
/// 数え上げ・中央分割・参照表の作成は中断すると色数が指定どおりにならないため中断しない）。
/// 上限は 8K・遅い環境・収束しにくい画像のための安全網である。
/// <b>縮小は時間で打ち切らない</b>: 反復が無い 1 回の走査であり、途中で打ち切ると画像の一部が書かれないまま
/// 返るためである（費用は寸法から予測できる。 <see cref="EsReadOnlyBitmap.Resize(int, EsImageQuality)"/> の備考）。<br/>
/// <b>画素ごとに厳密な最近傍を採らない理由</b>: 減色は<b>使われている箱ごとに 1 度だけ最近傍を求め、
/// 画素はその参照表を引く</b>形である。 画素そのものから最近傍を求めると知覚誤差は小さくなるが、
/// <b>費用は「画素の数 × 色数」で決まる</b>（逐次であり、画素数と色数の積に比例する）ため、
/// <b>最も速い段階でも採るには高すぎる</b>。 参照表が効くのは
/// <b>箱の数が画素の数よりずっと少ない</b>ためである。 また箱の代表色は<b>その箱に入っている画素の平均色</b>で
/// あるため、平坦な色の画像（画面キャプチャ）では画素ごとの結果と一致し、<b>改善しない</b>。
///
/// <b>減色の所要の内訳</b>: <b>画素ごとの走査（数え上げと書き込み）は品質に依らない</b>
/// （所要の差は詰め直しの回数だけである）。 平坦な色の画像は詰め直しが収束するため品質に依らない。
///
/// <b>見た目の差が最も大きいのはディザ</b>であるため、減色では <see cref="EsDitherMode"/> も併せて指定する
/// （<b>色数が内容に対して足りないときだけ</b>。 <see cref="EsDitherMode"/> の備考を参照する）。
/// </remarks>
public enum EsImageQuality
{
    /// <summary>最速（画質は最も低い）。</summary>
    Low,

    /// <summary>速度と画質の釣り合い（既定）。</summary>
    Mid,

    /// <summary>最も画質が高い（最も遅い場合がある）。</summary>
    High,
}
